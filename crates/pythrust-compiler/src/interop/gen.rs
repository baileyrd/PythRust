//! The generated crate (`docs/research/rust-interop.md#the-shim`): its
//! manifest, and one `extern "C"` shim per stub function the program
//! calls, each from one fixed template.

use crate::ast::{StubDef, TypeExpr};
use crate::diag::{DiagKind, Diagnostic, Result};
use crate::span::Span;

/// The generated crate's name; its staticlib replaces the plain runtime.
pub const CRATE: &str = "pythrust_bindings";

/// Words a Rust path cannot spell even as a raw identifier (`r#...`).
const PATH_WORDS: &[&str] = &["self", "Self", "super", "crate", "_"];

/// Crate names the generated crate already uses or cannot depend on.
const TAKEN_CRATES: &[&str] = &[
    "std",
    "core",
    "alloc",
    "proc_macro",
    "test",
    "pythrust_rt",
    CRATE,
];

/// Whether `name` cannot name a binding's crate.
pub fn reserved_crate(name: &str) -> bool {
    PATH_WORDS.contains(&name) || TAKEN_CRATES.contains(&name)
}

/// The C symbol of the shim for the stub `dotted` (`binding.func`). Each
/// part is length-prefixed, so no two binding and function names collide.
pub fn symbol(dotted: &str) -> String {
    let (binding, func) = dotted.split_once('.').unwrap_or(("", dotted));
    format!("pt_rs_{}{binding}_{}{func}", binding.len(), func.len())
}

/// A type that crosses the boundary
/// (`docs/research/rust-interop.md#types-across-the-boundary`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Cross {
    Int,
    Float,
    Bool,
    Str,
    Bytes,
    /// A result only.
    None,
}

impl Cross {
    /// The type `t` names; the parser admits only these in a stub.
    fn of(t: &TypeExpr) -> Result<Cross> {
        let cross = match t.name.name.as_str() {
            _ if !t.args.is_empty() || t.optional => None,
            "int" => Some(Cross::Int),
            "float" => Some(Cross::Float),
            "bool" => Some(Cross::Bool),
            "str" => Some(Cross::Str),
            "bytes" => Some(Cross::Bytes),
            "None" => Some(Cross::None),
            _ => None,
        };
        cross.ok_or_else(|| gap(t.span, "a stub type that does not cross into Rust"))
    }

    /// The shim's C type for a parameter of this type.
    fn c_param(self) -> &'static str {
        match self {
            Cross::Int => "i64",
            Cross::Float => "f64",
            Cross::Bool | Cross::None => "u8",
            Cross::Str => "*const pythrust_rt::abi::Str",
            Cross::Bytes => "*const pythrust_rt::abi::Bytes",
        }
    }

    /// The shim's C type for a result of this type.
    fn c_result(self) -> &'static str {
        match self {
            Cross::Str => "*mut pythrust_rt::abi::Str",
            Cross::Bytes => "*mut pythrust_rt::abi::Bytes",
            other => other.c_param(),
        }
    }

    /// The Rust argument made from the shim's parameter `p`.
    fn arg(self, p: &str) -> String {
        match self {
            Cross::Bool => format!("pythrust_rt::abi::arg_bool({p})"),
            Cross::Str => format!("pythrust_rt::abi::arg_str(&{p})"),
            Cross::Bytes => format!("pythrust_rt::abi::arg_bytes(&{p})"),
            Cross::Int | Cross::Float | Cross::None => p.to_string(),
        }
    }

    /// The Rust function's result type, which the shim names, so rustc
    /// rejects a stub that disagrees.
    fn rust_result(self) -> &'static str {
        match self {
            Cross::Int => "i64",
            Cross::Float => "f64",
            Cross::Bool => "bool",
            Cross::Str => "String",
            Cross::Bytes => "Vec<u8>",
            Cross::None => "()",
        }
    }
}

fn gap(span: Span, message: &str) -> Diagnostic {
    Diagnostic {
        span,
        message: message.to_string(),
        kind: DiagKind::Backend,
    }
}

/// A binding the generated crate depends on: its name, which shims call
/// it by, its Cargo package's name, and its directory.
#[derive(Debug, Clone, Copy)]
pub struct Dep<'a> {
    pub name: &'a str,
    pub package: &'a str,
    pub dir: &'a str,
}

/// `Cargo.toml` of the generated crate: a staticlib over `pythrust-rt`
/// at `runtime` and each `(name, dir)` binding, its own workspace, with
/// panics unwinding in both profiles. Paths come quoted and escaped.
pub fn manifest(runtime: &str, bindings: &[Dep]) -> String {
    let deps: String = bindings
        .iter()
        .map(|d| {
            format!(
                "{} = {{ package = {}, path = {} }}\n",
                d.name,
                toml_string(d.package),
                toml_string(d.dir)
            )
        })
        .collect();
    format!(
        "# Generated by pythrust; rewritten every build.\n\
         [package]\nname = \"{CRATE}\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [lib]\npath = \"lib.rs\"\ncrate-type = [\"staticlib\"]\n\n\
         [dependencies]\npythrust-rt = {{ path = {} }}\n{deps}\n\
         [profile.dev]\npanic = \"unwind\"\n\n[profile.release]\npanic = \"unwind\"\n\n\
         [workspace]\n",
        toml_string(runtime)
    )
}

/// `text` as a TOML basic string: quotes, backslashes and control
/// characters escaped.
pub fn toml_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The shim comment's prefix; [`stub_of`] finds the comment again.
const STUB_MARK: &str = "// stub ";

/// `lib.rs` of the generated crate: the runtime linked in, then one shim
/// per stub, each under a comment naming its stub's place, which
/// `locate` gives (`fastfs.pyr:1`).
pub fn shims(stubs: &[StubDef], locate: &dyn Fn(Span) -> String) -> Result<String> {
    let mut out = String::from(
        "//! Generated by pythrust from the bindings' stubs; rewritten every build.\n\n\
         extern crate pythrust_rt;\n",
    );
    for stub in stubs {
        out.push('\n');
        out.push_str(&shim(stub, locate)?);
    }
    Ok(out)
}

/// One shim, from the fixed template
/// (`docs/research/rust-interop.md#the-shim`): raw parameters `p0..`
/// and the call's site in; one `unsafe` block converts them; `call` (or
/// `call_raising`, for a stub that `raises`) runs the function, whose
/// result type the closure names, so rustc checks it against the stub.
fn shim(stub: &StubDef, locate: &dyn Fn(Span) -> String) -> Result<String> {
    let dotted = &stub.name.name;
    let (binding, func) = dotted.split_once('.').unwrap_or(("", dotted));
    if PATH_WORDS.contains(&func) {
        return Err(Diagnostic {
            span: stub.name.span,
            message: format!("a Rust function named `{func}` cannot be called; rename it"),
            kind: DiagKind::Backend,
        });
    }
    let params = stub
        .params
        .iter()
        .map(|p| Cross::of(&p.annotation))
        .collect::<Result<Vec<_>>>()?;
    let ret = Cross::of(&stub.returns)?;
    let decl: String = params
        .iter()
        .enumerate()
        .map(|(i, c)| format!("    p{i}: {},\n", c.c_param()))
        .collect();
    let mut names: Vec<String> = (0..params.len()).map(|i| format!("a{i}")).collect();
    let mut values: Vec<String> = params
        .iter()
        .enumerate()
        .map(|(i, c)| c.arg(&format!("p{i}")))
        .collect();
    let args = names.join(", ");
    names.push("at".to_string());
    values.push(SITE.to_string());
    let (call, result) = match stub.raises.is_empty() {
        true => ("call", ret.rust_result().to_string()),
        false => (
            "call_raising",
            format!("std::io::Result<{}>", ret.rust_result()),
        ),
    };
    Ok(format!(
        "{STUB_MARK}{}: the stub for `{func}`\n\
         #[unsafe(no_mangle)]\n\
         pub unsafe extern \"C\" fn {}(\n{decl}    \
         head: *const u8, head_len: usize, tail: *const u8, tail_len: usize,\n\
         ) -> {} {{\n    \
         // SAFETY: generated code passes live values and a static site.\n    \
         let {} = unsafe {{ {} }};\n    \
         pythrust_rt::abi::{call}(at, || -> {result} {{ r#{binding}::r#{func}({args}) }})\n}}\n",
        one_line(&locate(stub.span)),
        symbol(dotted),
        ret.c_result(),
        tuple(&names),
        tuple(&values),
    ))
}

/// The call's site, from the shim's last four parameters.
const SITE: &str = "pythrust_rt::abi::site(head, head_len, tail, tail_len)";

/// `items` as a tuple, or the one item alone.
fn tuple(items: &[String]) -> String {
    match items {
        [one] => one.clone(),
        _ => format!("({})", items.join(", ")),
    }
}

/// `text` with control characters escaped, so a file name cannot end
/// the shim's comment and write code.
fn one_line(text: &str) -> String {
    text.chars()
        .map(|c| match c.is_control() {
            true => c.escape_default().to_string(),
            false => c.to_string(),
        })
        .collect()
}

/// The stub a line of the generated `lib.rs` belongs to, as its comment
/// names it (`fastfs.pyr:1: the stub for `f``), for a rustc error at
/// 1-based `line`; `None` outside every shim.
pub fn stub_of(lib: &str, line: usize) -> Option<&str> {
    lib.lines()
        .take(line)
        .collect::<Vec<_>>()
        .into_iter()
        .rev()
        .find_map(|l| l.strip_prefix(STUB_MARK))
}

