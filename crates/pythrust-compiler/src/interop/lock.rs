//! `pythrust.lock` (M6d, `docs/research/package-tool.md#how-build-uses-the-lock`):
//! the generated crate's `Cargo.lock`, verbatim, under [`HEADER`]. This
//! reads it, finds a git package (not supported yet), and names the
//! entries of a build's resolution it does not cover, for the
//! stale-lock error.
//!
//! Only the parts of a lockfile this needs are read: each `[[package]]`'s
//! `name`, `version`, `source`, `checksum` and `dependencies`.

/// The first line of `pythrust.lock`, above cargo's own header.
pub const HEADER: &str = "# Generated by pythrust lock; do not edit.";

/// `text` with [`HEADER`]'s line taken off, as cargo reads the lock.
pub fn strip_header(text: &str) -> &str {
    let Some(rest) = text.strip_prefix(HEADER) else {
        return text;
    };
    rest.strip_prefix("\r\n")
        .or_else(|| rest.strip_prefix('\n'))
        .unwrap_or(rest)
}

/// The `pythrust.lock` holding cargo's lock `text`.
pub fn with_header(text: &str) -> String {
    format!("{HEADER}\n{text}")
}

use std::collections::BTreeSet;

/// One `[[package]]` of a `Cargo.lock`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package {
    pub name: String,
    pub version: String,
    /// `None` for a path package (the binding itself, a local crate).
    pub source: Option<String>,
    pub checksum: Option<String>,
    /// As written: `name`, `name version` or `name version (source)`.
    pub deps: Vec<String>,
}

/// A parsed `Cargo.lock`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lock {
    /// The `version = N` format line; 0 when absent (format 1).
    pub format: u32,
    pub packages: Vec<Package>,
}

/// Parses the `Cargo.lock` `text`.
pub fn parse(text: &str) -> Result<Lock, String> {
    let mut lock = Lock {
        format: 0,
        packages: Vec::new(),
    };
    let mut current: Option<Package> = None;
    let mut in_deps = false;
    // Keys of a table other than `[[package]]`, such as cargo's
    // `[[patch.unused]]`, are not read.
    let mut in_table = false;
    for (i, raw) in text.lines().enumerate() {
        let line = raw.trim();
        let bad = || format!("Cargo.lock line {}: cannot read `{line}`", i + 1);
        if in_deps {
            in_deps = deps_line(line, current.as_mut()).ok_or_else(bad)?;
            continue;
        }
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with('[') {
            lock.packages.extend(current.take());
            in_table = true;
            if line == "[[package]]" {
                current = Some(empty_package());
            }
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(bad());
        };
        let (key, value) = (key.trim(), value.trim());
        match (key, current.as_mut()) {
            ("version", None) if !in_table => lock.format = value.parse().map_err(|_| bad())?,
            ("dependencies", Some(_)) => {
                in_deps = value != "[]";
                if value != "[" && value != "[]" {
                    return Err(bad());
                }
            }
            (_, Some(p)) => set_field(p, key, unquote(value).ok_or_else(bad)?),
            (_, None) => {}
        }
    }
    lock.packages.extend(current);
    Ok(lock)
}

fn empty_package() -> Package {
    Package {
        name: String::new(),
        version: String::new(),
        source: None,
        checksum: None,
        deps: Vec::new(),
    }
}

/// One line inside `dependencies = [`; whether the list goes on.
fn deps_line(line: &str, package: Option<&mut Package>) -> Option<bool> {
    if line == "]" {
        return Some(false);
    }
    let dep = unquote(line.strip_suffix(',').unwrap_or(line))?;
    package?.deps.push(dep);
    Some(true)
}

fn set_field(p: &mut Package, key: &str, value: String) {
    match key {
        "name" => p.name = value,
        "version" => p.version = value,
        "source" => p.source = Some(value),
        "checksum" => p.checksum = Some(value),
        _ => {}
    }
}

/// The text of a `"..."` TOML string with no escapes, as cargo writes
/// every lockfile value.
fn unquote(value: &str) -> Option<String> {
    let inner = value.strip_prefix('"')?.strip_suffix('"')?;
    (!inner.contains(['"', '\\'])).then(|| inner.to_string())
}

impl Package {
    fn is_git(&self) -> bool {
        self.source
            .as_deref()
            .is_some_and(|s| s.starts_with("git+"))
    }

    /// Name and version: what the user knows the entry by.
    fn label(&self) -> String {
        format!("{} {}", self.name, self.version)
    }

    fn id(&self) -> Id<'_> {
        (&self.name, &self.version, self.source.as_deref())
    }

    /// Whether `other` has this entry's name, version and source.
    fn same_id(&self, other: &Package) -> bool {
        self.id() == other.id()
    }
}

impl Lock {
    /// The entry with `p`'s name, version and source.
    fn find(&self, p: &Package) -> Option<&Package> {
        self.packages.iter().find(|q| q.same_id(p))
    }

    /// `p`'s dependencies, each the entry of this lock it names; `None`
    /// when one names no single entry. Cargo writes a bare name or leaves
    /// out the source when that is enough to tell entries apart, which
    /// differs between a lock and its subset, so each is read against
    /// this lock and compared by name, version and source.
    fn edges(&self, p: &Package) -> Option<BTreeSet<Id<'_>>> {
        p.deps.iter().map(|dep| self.named(dep)).collect()
    }

    /// The one entry the dependency `dep` names: `name`, `name version`
    /// or `name version (source)`.
    fn named(&self, dep: &str) -> Option<Id<'_>> {
        let mut parts = dep.splitn(3, ' ');
        let name = parts.next()?;
        let version = parts.next();
        let source = match parts.next() {
            Some(s) => Some(s.strip_prefix('(')?.strip_suffix(')')?),
            None => None,
        };
        let mut found = self.packages.iter().filter(|q| {
            q.name == name
                && version.is_none_or(|v| q.version == v)
                && source.is_none_or(|s| q.source.as_deref() == Some(s))
        });
        let first = found.next()?;
        found.next().is_none().then(|| first.id())
    }
}

/// An entry's identity: name, version and source.
type Id<'a> = (&'a str, &'a str, Option<&'a str>);

/// The first git package of `lock`: its commit is not pinned the way a
/// registry version is, so it is not supported yet.
pub fn git_package(lock: &Lock) -> Option<&Package> {
    lock.packages.iter().find(|p| p.is_git())
}

/// An entry of a build's lock that `pythrust.lock` does not hold.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Change {
    /// No entry of that name, version and source.
    Added(String),
    /// Same name, version and source; another checksum, or a dependency
    /// the locked entry does not have.
    Changed(String),
}

impl std::fmt::Display for Change {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Change::Added(p) => write!(f, "added `{p}`"),
            Change::Changed(p) => write!(f, "changed `{p}`"),
        }
    }
}

/// Each entry of `built`, cargo's resolution for one program, that
/// `locked` does not cover, leaving out the generated crate `root`
/// itself. A program may import only some bindings, so `built` may drop
/// entries, and an entry may lose dependencies a dropped binding's
/// features added; anything else is new. So a binding that starts
/// depending on a crate already in the lock shows as changed.
pub fn uncovered(built: &Lock, locked: &Lock, root: &str) -> Vec<Change> {
    let mut out = Vec::new();
    let is_root = |p: &&Package| p.name == root && p.source.is_none();
    for p in built.packages.iter().filter(|p| !is_root(p)) {
        let Some(q) = locked.find(p) else {
            out.push(Change::Added(p.label()));
            continue;
        };
        let edges = built.edges(p).zip(locked.edges(q));
        let covered = q.checksum == p.checksum && edges.is_some_and(|(b, l)| b.is_subset(&l));
        if !covered {
            out.push(Change::Changed(p.label()));
        }
    }
    out
}

