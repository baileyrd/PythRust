use super::*;

const REG: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// The generated crate `lock_text` writes first.
const ROOT: (&str, &str) = ("root", "0.1.0");

/// A lock with the path package `root` depending on `deps`, then each
/// registry package of `pkgs`: `(name, version, deps)`.
fn lock_text(root: &str, deps: &[&str], pkgs: &[(&str, &str, &[&str])]) -> String {
    let mut out = String::from("# This file is automatically @generated by Cargo.\nversion = 4\n");
    let list = |deps: &[&str]| {
        if deps.is_empty() {
            return String::new();
        }
        let items: Vec<String> = deps.iter().map(|d| format!(" \"{d}\",\n")).collect();
        format!("dependencies = [\n{}]\n", items.concat())
    };
    out.push_str(&format!(
        "\n[[package]]\nname = \"{root}\"\nversion = \"0.1.0\"\n{}",
        list(deps)
    ));
    for (name, version, deps) in pkgs {
        out.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"{REG}\"\nchecksum = \"sum-{name}-{version}\"\n{}",
            list(deps)
        ));
    }
    out
}

fn lock(root: &str, deps: &[&str], pkgs: &[(&str, &str, &[&str])]) -> Lock {
    parse(&lock_text(root, deps, pkgs)).unwrap_or_else(|e| panic!("{e}"))
}

#[test]
fn parse_reads_packages_and_dependencies() {
    let l = lock("fastfs", &["itoa"], &[("itoa", "1.0.1", &[])]);
    assert_eq!(l.format, 4);
    assert_eq!(l.packages.len(), 2);
    assert_eq!(l.packages[0].source, None);
    assert_eq!(l.packages[0].deps, ["itoa"]);
    let itoa = &l.packages[1];
    assert_eq!(
        (itoa.name.as_str(), itoa.version.as_str()),
        ("itoa", "1.0.1")
    );
    assert_eq!(itoa.source.as_deref(), Some(REG));
    assert_eq!(itoa.checksum.as_deref(), Some("sum-itoa-1.0.1"));
}

#[test]
fn parse_rejects_what_cargo_never_writes() {
    for bad in [
        "[[package]]\nname = fastfs\n",
        "[[package]]\noops\n",
        "version = x\n",
    ] {
        assert!(parse(bad).is_err(), "{bad}");
    }
    let err = parse("[[package]]\nname = \"a\\\"b\"\n")
        .err()
        .unwrap_or_default();
    assert!(err.starts_with("Cargo.lock line 2:"), "{err}");
}

#[test]
fn the_header_goes_on_and_comes_off() {
    let cargo = lock_text("a", &[], &[]);
    let ours = with_header(&cargo);
    assert!(ours.starts_with("# Generated by pythrust lock; do not edit.\n# This file"));
    assert_eq!(strip_header(&ours), cargo);
    let crlf = ours.replacen('\n', "\r\n", 1);
    assert_eq!(strip_header(&crlf), cargo);
    // A lock without the header is read as it is.
    assert_eq!(strip_header(&cargo), cargo);
    assert_eq!(parse(&ours), parse(&cargo));
}

#[test]
fn a_git_package_is_found() {
    let text = lock_text("a", &["g"], &[("itoa", "1.0.1", &[])])
        + "\n[[package]]\nname = \"g\"\nversion = \"0.1.0\"\nsource = \"git+https://example.com/g#abc\"\n";
    let l = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(git_package(&l).map(|p| p.name.as_str()), Some("g"));
    let plain = lock("a", &["itoa"], &[("itoa", "1.0.1", &[])]);
    assert_eq!(git_package(&plain), None);
}

#[test]
fn the_same_resolution_is_covered() {
    let a = lock("a", &["itoa"], &[("itoa", "1.0.1", &[])]);
    assert_eq!(uncovered(&a, &a.clone(), ROOT), []);
}

/// A program importing one of two bindings resolves a subset: dropped
/// entries are covered, and a bare dependency name in the subset means
/// the version the full lock qualifies.
#[test]
fn a_subset_is_covered() {
    let full = lock(
        "root",
        &["a", "b"],
        &[
            ("a", "0.1.0", &["itoa 1.0.1"]),
            ("b", "0.1.0", &["itoa 0.4.8"]),
            ("itoa", "1.0.1", &[]),
            ("itoa", "0.4.8", &[]),
        ],
    );
    let subset = lock(
        "root",
        &["a"],
        &[("a", "0.1.0", &["itoa"]), ("itoa", "1.0.1", &[])],
    );
    assert_eq!(uncovered(&subset, &full, ROOT), []);
}

#[test]
fn new_pins_and_edges_are_not_covered() {
    let locked = lock(
        "root",
        &["a"],
        &[
            ("a", "0.1.0", &[]),
            ("itoa", "1.0.1", &[]),
            ("ryu", "1.0.0", &[]),
        ],
    );
    // `a` now depends on `ryu`, already in the lock: only its edges show it.
    let built = lock(
        "root",
        &["a"],
        &[
            ("a", "0.1.0", &["itoa", "ryu"]),
            ("itoa", "1.0.9", &[]),
            ("ryu", "1.0.0", &[]),
        ],
    );
    let got: Vec<String> = uncovered(&built, &locked, ROOT)
        .iter()
        .map(Change::to_string)
        .collect();
    assert_eq!(got, ["changed `a 0.1.0`", "added `itoa 1.0.9`"]);
}

#[test]
fn another_checksum_or_source_is_not_covered() {
    let old = lock("root", &["itoa"], &[("itoa", "1.0.1", &[])]);
    let text = lock_text("root", &["itoa"], &[("itoa", "1.0.1", &[])]);
    let sum = parse(&text.replace("sum-itoa", "other")).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(
        uncovered(&sum, &old, ROOT),
        [Change::Changed("itoa 1.0.1".into())]
    );
    let mirror = parse(&text.replace(REG, "sparse+https://mirror.example/"))
        .unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(
        uncovered(&mirror, &old, ROOT),
        [Change::Added("itoa 1.0.1".into())]
    );
}

/// Cargo lists a `[patch]` it did not use under `[[patch.unused]]`,
/// whose `version` is a package's, not the format's.
#[test]
fn patch_unused_is_not_read() {
    let text = lock_text("a", &[], &[]) + "\n[[patch.unused]]\nname = \"p\"\nversion = \"0.1.0\"\n";
    let l = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(l.format, 4);
    assert_eq!(l.packages.len(), 1);
}

/// Only the generated crate itself, a path package, is left out: a
/// registry crate of its name is checked like any other.
#[test]
fn only_the_path_root_is_left_out() {
    let locked = lock("root", &[], &[]);
    let built = lock("root", &["root"], &[("root", "1.0.0", &[])]);
    assert_eq!(
        uncovered(&built, &locked, ROOT),
        [Change::Added("root 1.0.0".into())]
    );
}

/// Two entries of one name and version from different sources: an edge
/// is known by its source too, so moving it from one to the other is a
/// change, even though both entries stay in the lock.
#[test]
fn an_edge_that_switches_source_is_not_covered() {
    const MIRROR: &str = "sparse+https://mirror.example/";
    let text = |source: &str| {
        let dep = format!("foo 1.0.0 ({source})");
        lock_text("root", &["a"], &[("a", "0.1.0", &[dep.as_str()]), ("foo", "1.0.0", &[])])
            + &format!("\n[[package]]\nname = \"foo\"\nversion = \"1.0.0\"\nsource = \"{MIRROR}\"\nchecksum = \"sum-mirror\"\n")
    };
    let parsed = |source: &str| parse(&text(source)).unwrap_or_else(|e| panic!("{e}"));
    let locked = parsed(REG);
    assert_eq!(uncovered(&parsed(REG), &locked, ROOT), []);
    assert_eq!(
        uncovered(&parsed(MIRROR), &locked, ROOT),
        [Change::Changed("a 0.1.0".into())]
    );
}

/// A dependency that names no single entry of its lock is never covered.
#[test]
fn an_unresolved_edge_is_not_covered() {
    let locked = lock("root", &["a"], &[("a", "0.1.0", &["gone"])]);
    assert_eq!(
        uncovered(&locked.clone(), &locked, ROOT),
        [Change::Changed("a 0.1.0".into())]
    );
}

/// A binding whose package shares the generated crate's name, at
/// another version, is checked like any other path package.
#[test]
fn a_path_package_named_like_the_root_is_checked() {
    let locked = lock("root", &[], &[]);
    let text = lock_text("root", &["root 2.0.0"], &[])
        + "\n[[package]]\nname = \"root\"\nversion = \"2.0.0\"\n";
    let built = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(
        uncovered(&built, &locked, ROOT),
        [Change::Added("root 2.0.0".into())]
    );
}

#[test]
fn removed_names_what_a_new_lock_dropped() {
    let old = lock(
        "root",
        &["a"],
        &[("a", "0.1.0", &[]), ("itoa", "1.0.1", &[])],
    );
    let new = lock("root", &[], &[("itoa", "1.0.1", &[])]);
    assert_eq!(
        removed(&old, &new, ROOT),
        [Change::Removed("a 0.1.0".into())]
    );
    assert_eq!(removed(&old, &old, ROOT), []);
}
