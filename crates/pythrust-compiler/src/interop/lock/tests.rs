use super::*;

const REG: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// A lock with the path package `root` depending on `deps`, then each
/// registry package of `pkgs`: `(name, version, deps)`.
fn lock_text(root: &str, deps: &[&str], pkgs: &[(&str, &str, &[&str])]) -> String {
    let mut out = String::from("# This file is automatically @generated by Cargo.\nversion = 4\n");
    let list = |deps: &[&str]| {
        if deps.is_empty() {
            return String::new();
        }
        let items: Vec<String> = deps.iter().map(|d| format!(" \"{d}\",\n")).collect();
        format!("dependencies = [\n{}]\n", items.concat())
    };
    out.push_str(&format!(
        "\n[[package]]\nname = \"{root}\"\nversion = \"0.1.0\"\n{}",
        list(deps)
    ));
    for (name, version, deps) in pkgs {
        out.push_str(&format!(
            "\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"{REG}\"\nchecksum = \"sum-{name}-{version}\"\n{}",
            list(deps)
        ));
    }
    out
}

fn lock(root: &str, deps: &[&str], pkgs: &[(&str, &str, &[&str])]) -> Lock {
    parse(&lock_text(root, deps, pkgs)).unwrap_or_else(|e| panic!("{e}"))
}

#[test]
fn parse_reads_packages_and_dependencies() {
    let l = lock("fastfs", &["itoa"], &[("itoa", "1.0.1", &[])]);
    assert_eq!(l.format, 4);
    assert_eq!(l.packages.len(), 2);
    assert_eq!(l.packages[0].source, None);
    assert_eq!(l.packages[0].deps, ["itoa"]);
    let itoa = &l.packages[1];
    assert_eq!(
        (itoa.name.as_str(), itoa.version.as_str()),
        ("itoa", "1.0.1")
    );
    assert!(itoa.is_pinned());
    assert_eq!(itoa.checksum.as_deref(), Some("sum-itoa-1.0.1"));
}

#[test]
fn parse_rejects_what_cargo_never_writes() {
    for bad in [
        "[[package]]\nname = fastfs\n",
        "[[package]]\noops\n",
        "version = x\n",
    ] {
        assert!(parse(bad).is_err(), "{bad}");
    }
    let err = parse("[[package]]\nname = \"a\\\"b\"\n")
        .err()
        .unwrap_or_default();
    assert!(err.starts_with("Cargo.lock line 2:"), "{err}");
}

#[test]
fn resolved_names_the_only_version_or_the_written_one() {
    let l = lock(
        "a",
        &["itoa 0.4.8", "itoa 1.0.1", "memchr"],
        &[
            ("itoa", "0.4.8", &[]),
            ("itoa", "1.0.1", &[]),
            ("memchr", "2.7.1", &[]),
        ],
    );
    let r = l.resolved(&l.packages[0]);
    let versions = |name: &str| r.get(name).map(|vs| vs.iter().cloned().collect::<Vec<_>>());
    assert_eq!(versions("memchr"), Some(vec!["2.7.1".to_string()]));
    assert_eq!(
        versions("itoa"),
        Some(vec!["0.4.8".to_string(), "1.0.1".to_string()])
    );
}

#[test]
fn seed_is_the_union_with_qualified_dependencies() {
    let a = lock("a", &["b"], &[("b", "1.0.0", &["c"]), ("c", "0.2.0", &[])]);
    let b = lock("b2", &["d"], &[("d", "3.1.0", &[]), ("c", "0.2.0", &[])]);
    let text = seed(&[("a", &a), ("b2", &b)]).unwrap_or_default();
    assert!(text.starts_with("# Seeded by pythrust"), "{text}");
    let seeded = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(seeded.format, 4);
    let names: Vec<_> = seeded.packages.iter().map(|p| p.name.as_str()).collect();
    assert_eq!(names, ["a", "b", "b2", "c", "d"]);
    assert_eq!(seeded.packages[0].source, None, "a binding keeps its edges");
    assert_eq!(seeded.packages[0].deps, ["b 1.0.0"]);
    assert_eq!(seeded.packages[1].deps, ["c 0.2.0"]);
}

#[test]
fn compatible_follows_cargo() {
    assert!(compatible("1.0.1", "1.0.9"));
    assert!(compatible("1.2.0", "1.9.3"));
    assert!(!compatible("0.4.8", "1.0.1"));
    assert!(compatible("0.4.1", "0.4.8"));
    assert!(!compatible("0.4.8", "0.5.0"));
    assert!(!compatible("0.0.1", "0.0.2"));
    assert!(compatible("1.0.0-rc.1", "1.2.0"));
    assert!(!compatible("x", "1.0.0"));
}

#[test]
fn compatible_pins_in_two_bindings_are_drift() {
    let a = lock("a", &["itoa"], &[("itoa", "1.0.1", &[])]);
    let b = lock("b", &["itoa"], &[("itoa", "1.0.9", &[])]);
    let err = seed(&[("a", &a), ("b", &b)]).err();
    let Some(LockError::Drift { package, pins }) = err.clone() else {
        panic!("{err:?}");
    };
    assert_eq!(package, "itoa");
    assert_eq!(
        pins,
        [("a".into(), "1.0.1".into()), ("b".into(), "1.0.9".into())]
    );
    let shown = err.map(|e| e.to_string()).unwrap_or_default();
    assert!(
        shown.starts_with("bindings `a` and `b` pin `itoa`"),
        "{shown}"
    );
}

#[test]
fn incompatible_and_zero_zero_pins_coexist() {
    let a = lock(
        "a",
        &["itoa"],
        &[("itoa", "0.4.8", &[]), ("z", "0.0.1", &[])],
    );
    let b = lock(
        "b",
        &["itoa"],
        &[("itoa", "1.0.1", &[]), ("z", "0.0.2", &[])],
    );
    let text = seed(&[("a", &a), ("b", &b)]).unwrap_or_default();
    let seeded = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(seeded.packages.len(), 6, "four pins and the two bindings");
}

#[test]
fn git_dependencies_are_refused() {
    let text = lock_text("a", &["g"], &[])
        + "\n[[package]]\nname = \"g\"\nversion = \"0.1.0\"\nsource = \"git+https://example.com/g#abc\"\n";
    let a = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    let err = seed(&[("a", &a)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert_eq!(
        err,
        "binding `a`: git dependencies are not supported yet; use a crates.io version (`g`)"
    );
}

/// The lock cargo would write for the generated crate over binding `a`.
fn built(pkgs: &[(&str, &str, &[&str])]) -> Lock {
    lock("pythrust_bindings", &["a", "pythrust-rt"], pkgs)
}

#[test]
fn verify_accepts_the_same_resolution_and_dropped_entries() {
    // `dev` is a dev-dependency: pinned by the binding, absent from the build.
    let a = lock(
        "a",
        &["b", "dev"],
        &[
            ("b", "1.0.0", &["c"]),
            ("c", "0.2.0", &[]),
            ("dev", "2.0.0", &[]),
        ],
    );
    let ok = built(&[("b", "1.0.0", &["c"]), ("c", "0.2.0", &[])]);
    assert_eq!(verify(&ok, &[("a", &a)]), Ok(()));
}

#[test]
fn verify_keeps_an_older_pin() {
    let a = lock("a", &["itoa"], &[("itoa", "1.0.1", &[])]);
    let newer = built(&[("itoa", "1.0.9", &[])]);
    let err = verify(&newer, &[("a", &a)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert_eq!(
        err,
        "binding `a`: dependencies differ from its Cargo.lock (`itoa 1.0.9` is not pinned); \
         update and commit the binding's lockfile"
    );
}

#[test]
fn verify_refuses_an_entry_no_binding_pins() {
    let a = lock("a", &[], &[]);
    let added = built(&[("memchr", "2.7.1", &[])]);
    let err = verify(&added, &[("a", &a)]).err();
    assert_eq!(
        err,
        Some(LockError::Changed {
            binding: None,
            detail: "`memchr 2.7.1` is not pinned".into()
        })
    );
    let shown = err.map(|e| e.to_string()).unwrap_or_default();
    assert!(
        shown.starts_with("a binding: dependencies differ"),
        "{shown}"
    );
}

#[test]
fn verify_refuses_another_checksum() {
    let a = lock("a", &["b"], &[("b", "1.0.0", &[])]);
    let mut other = built(&[("b", "1.0.0", &[])]);
    other.packages[1].checksum = Some("tampered".into());
    let err = verify(&other, &[("a", &a)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert!(err.contains("`b 1.0.0` has another checksum"), "{err}");
}

#[test]
fn verify_compares_shared_edges_by_resolved_version() {
    // The binding writes `c` bare (one version); the build has two `c`s
    // and so writes them qualified.
    let a = lock("a", &["b"], &[("b", "1.0.0", &["c"]), ("c", "0.2.0", &[])]);
    let x = lock("x", &["c"], &[("c", "1.0.0", &[])]);
    let same = built(&[
        ("b", "1.0.0", &["c 0.2.0"]),
        ("c", "0.2.0", &[]),
        ("c", "1.0.0", &[]),
    ]);
    assert_eq!(verify(&same, &[("a", &a), ("x", &x)]), Ok(()));
    let moved = built(&[
        ("b", "1.0.0", &["c 1.0.0"]),
        ("c", "0.2.0", &[]),
        ("c", "1.0.0", &[]),
    ]);
    let err = verify(&moved, &[("a", &a), ("x", &x)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert!(
        err.starts_with("binding `a`: dependencies differ from its Cargo.lock (`b 1.0.0` depends on `c 1.0.0`, not `c 0.2.0`)"),
        "{err}"
    );
}

#[test]
fn other_registries_are_pinned_and_checked() {
    let sparse = "sparse+https://my-registry.example/index/";
    let text = lock_text("a", &["s"], &[])
        + &format!("\n[[package]]\nname = \"s\"\nversion = \"1.2.0\"\nsource = \"{sparse}\"\nchecksum = \"c\"\n");
    let a = parse(&text).unwrap_or_else(|e| panic!("{e}"));
    let seeded = seed(&[("a", &a)]).unwrap_or_default();
    assert!(
        seeded.contains(&format!(
            "name = \"s\"\nversion = \"1.2.0\"\nsource = \"{sparse}\""
        )),
        "{seeded}"
    );
    let mut newer = a.clone();
    newer.packages[1].version = "1.3.0".into();
    let err = verify(&newer, &[("a", &a)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert!(err.contains("s 1.3.0"), "{err}");
}

/// A binding's own edge moved to a version another binding pins: every
/// registry entry still matches, but the binding's edge does not.
#[test]
fn verify_checks_a_bindings_own_edges() {
    let a = lock("a", &["itoa"], &[("itoa", "0.4.8", &[])]);
    let b = lock("b", &["itoa"], &[("itoa", "1.0.1", &[])]);
    let built = lock(
        "pythrust_bindings",
        &["a", "b"],
        &[("itoa", "0.4.8", &[]), ("itoa", "1.0.1", &[])],
    );
    let mut moved = built.clone();
    moved.packages.push(Package {
        name: "a".into(),
        version: "0.1.0".into(),
        source: None,
        checksum: None,
        deps: vec!["itoa 1.0.1".into()],
    });
    let err = verify(&moved, &[("a", &a), ("b", &b)])
        .err()
        .map(|e| e.to_string())
        .unwrap_or_default();
    assert!(
        err.contains("`a 0.1.0` depends on `itoa 1.0.1`, not `itoa 0.4.8`"),
        "{err}"
    );
    let mut kept = built;
    kept.packages.push(Package {
        name: "a".into(),
        version: "0.1.0".into(),
        source: None,
        checksum: None,
        deps: vec!["itoa 0.4.8".into()],
    });
    assert_eq!(verify(&kept, &[("a", &a), ("b", &b)]), Ok(()));
}
